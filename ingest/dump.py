"""Phase 3 helper — dump chunks together with their embeddings as a txt file.

Produces ``artifacts/chunks_with_embeddings.txt``: for every chunk, the same
metadata as ``artifacts/chunks.txt`` plus the full 384-dim embedding vector
(``all-MiniLM-L6-v2``, L2-normalized, rounded to 4 decimals for readability).

The authoritative copy of the embeddings lives in the ChromaDB collection
(``chroma_db/``); this file is a human-readable mirror for inspection.

Usage
-----
    python -m ingest.dump
    python -m ingest.dump --out artifacts/embeddings_view.txt
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np

import config


def _format_embedding(vector: np.ndarray, per_row: int = 8, precision: int = 4) -> list[str]:
    """Format a vector as indexed rows of values, e.g. '0: 0.0012  1: -0.0043 ...'."""
    rounded = np.round(vector, precision).tolist()
    lines: list[str] = []
    for start in range(0, len(rounded), per_row):
        cells = "  ".join(
            f"{start + i}: {v:{precision + 3}.{precision}f}" for i, v in enumerate(rounded[start:start + per_row])
        )
        lines.append(cells)
    return lines


def write_chunks_with_embeddings_file(
    chunks: list,
    vectors: np.ndarray,
    path: Path = config.CHUNKS_WITH_EMBEDDINGS_FILE,
) -> Path:
    """Write each chunk's metadata, its embedding vector, then its text."""
    path.parent.mkdir(parents=True, exist_ok=True)
    rule = "=" * 80
    dim = vectors.shape[1] if len(vectors) else 0
    with path.open("w", encoding="utf-8") as fh:
        fh.write(f"{rule}\n")
        fh.write("Chunks with embeddings — generated by `python -m ingest.dump`\n")
        fh.write(f"Model: {config.EMBEDDING_MODEL} | dims: {dim} | chunks: {len(chunks)}\n")
        fh.write(
            "Embeddings are float32, L2-normalized, rounded to 4 decimals here. "
            "Authoritative copy: ChromaDB collection "
            f"'{config.COLLECTION_NAME}' at {config.VECTOR_DB_PATH}.\n"
        )
        fh.write(f"{rule}\n")

        for chunk, vector in zip(chunks, vectors):
            norm = float(np.linalg.norm(vector))
            fh.write(f"chunk: {chunk.chunk_id}\n")
            fh.write("metadata:\n")
            fh.write(f"  scheme: {chunk.scheme}\n")
            fh.write(f"  category: {chunk.category}\n")
            fh.write(f"  doc_type: {chunk.doc_type}\n")
            fh.write(f"  section: {chunk.section}\n")
            fh.write(f"  position: {chunk.position}\n")
            fh.write(f"  last_updated: {chunk.last_updated}\n")
            fh.write(f"  source_title: {chunk.source_title}\n")
            fh.write(f"  source_url: {chunk.source_url}\n")
            fh.write(f"embedding ({dim} dims, L2-normalized, L2 norm={norm:.4f}):\n")
            for line in _format_embedding(vector):
                fh.write(f"  {line}\n")
            fh.write("text:\n")
            fh.write(chunk.text)
            fh.write("\n\n")
    return path


def main(argv: list[str] | None = None) -> int:
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except (AttributeError, ValueError):
        pass

    parser = argparse.ArgumentParser(
        description="Dump chunks + embeddings to a readable txt file."
    )
    parser.add_argument(
        "--out", type=Path, default=config.CHUNKS_WITH_EMBEDDINGS_FILE,
        help="Output file (default: artifacts/chunks_with_embeddings.txt).",
    )
    args = parser.parse_args(argv)

    from ingest.chunk import chunk_all
    from ingest.embed import embed_texts

    chunks = chunk_all()
    vectors = embed_texts([c.text for c in chunks])
    print(f"Embedded {vectors.shape[0]} chunks, dim={vectors.shape[1]}")

    out = write_chunks_with_embeddings_file(chunks, vectors, args.out)
    size_kb = out.stat().st_size / 1024
    norms = np.linalg.norm(vectors, axis=1)
    print(f"Wrote {len(chunks)} chunks + embeddings to {out} ({size_kb:.0f} KB)")
    print(f"Embedding norms: min={norms.min():.6f} max={norms.max():.6f} (expect ~1.0)")
    return 0


if __name__ == "__main__":
    sys.exit(main())